/** Unknown service details are preserved, never guessed or hidden. */
export function translateRuntimeMessage(message: string, language: 'zh-CN' | 'en'): string {
  if (language !== 'en' || !/\p{Script=Han}/u.test(message)) return message
  if (message.startsWith('Additional details: ')) return message
  if (messages[message]) return messages[message]
  const submittedSuffix = ' 本次可能已提交，请先在专用窗口核对后再手动重试。'
  if (message.endsWith(submittedSuffix)) {
    return `${translateRuntimeMessage(message.slice(0, -submittedSuffix.length), language)} This request may already have been submitted. Check the dedicated browser before retrying manually.`
  }
  // Electron may wrap an application error when it crosses an IPC boundary.
  const ipcError = message.match(/^(Error invoking remote method '[^']+': (?:Error: )?)([\s\S]+)$/)
  if (ipcError) return ipcError[1] + translateRuntimeMessage(ipcError[2], language)
  if (message.startsWith('Error: ')) return 'Error: ' + translateRuntimeMessage(message.slice(7), language)
  for (const [pattern, render] of templates) {
    const match = message.match(pattern)
    if (match) return render(...match.slice(1))
  }
  return 'Additional details: ' + message
}
